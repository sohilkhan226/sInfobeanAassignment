# Assignment 4: Area of Rectangle

# Write a Python program that:

# Accepts length and breadth.
# Calculates area.

# Input:
# Length = 10
# Breadth = 5

# Output:
# Area = 50


length = float(input("Enter length: "))
breadth = float(input("Enter breadth: "))

area = length * breadth

print("Area =", area)